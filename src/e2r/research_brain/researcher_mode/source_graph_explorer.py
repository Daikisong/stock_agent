def _coverage_labels(rows: Sequence[str | Mapping[str, Any]]) -> set[str]:
    labels = set()
    for row in rows:
        if isinstance(row, str):
            value = row
        else:
            value = str(
                row.get("source_family")
                or row.get("route_id")
                or row.get("coverage_id")
                or ""
            )
        if value.strip():
            labels.add(value.strip().upper())
    return labels


def _observed_date(row: Mapping[str, Any]) -> date | None:
    raw = next(
        (
            str(row.get(key)).strip()
            for key in ("published_at", "publication_date", "filed_at", "observed_at")
            if row.get(key)
        ),
        "",
    )
    if not raw:
        return None
    try:
        return date.fromisoformat(raw[:10])
    except ValueError as exc:
        raise ValueError(f"invalid source graph date: {raw}") from exc


