def load_source_graph_checkpoint(path: str | Path) -> Mapping[str, Any]:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(payload, Mapping):
        raise ValueError("source graph checkpoint must be an object")
    return validate_source_graph_checkpoint(payload)


def validate_source_graph_checkpoint(
    checkpoint: Mapping[str, Any],
    *,
    target_id: str | None = None,
    as_of_date: str | None = None,
) -> Mapping[str, Any]:
    """Validate an in-memory Source Graph checkpoint before downstream use."""

    payload = dict(checkpoint)
    expected_hash = _checkpoint_hash(payload)
    if payload.get("checkpoint_hash") != expected_hash:
        raise ValueError("source graph checkpoint hash mismatch")
    required = ("checkpoint_id", "target_id", "as_of_date", "epoch")
    if any(payload.get(key) in {None, ""} for key in required):
        raise ValueError("source graph checkpoint identity is incomplete")
    if isinstance(payload["epoch"], bool) or int(payload["epoch"]) <= 0:
        raise ValueError("source graph checkpoint epoch must be positive")
    if any(
        bool(payload.get(key))
        for key in (
            "production_score_authority",
            "parser_field_direct_score_authority",
            "snippet_evidence_allowed",
            "transport_budget_can_complete_research",
        )
    ):
        raise ValueError("source graph checkpoint violates Evidence OS authority")
    cutoff = date.fromisoformat(str(payload["as_of_date"]))
    expected_id = stable_intelligence_id(
        "SGCHECK",
        {
            "target_id": payload["target_id"],
            "as_of_date": payload["as_of_date"],
            "epoch": payload["epoch"],
            "checkpoint_hash": expected_hash,
        },
    )
    if payload.get("checkpoint_id") != expected_id:
        raise ValueError("source graph checkpoint id mismatch")
    if target_id is not None and str(payload["target_id"]) != target_id:
        raise ValueError("source graph checkpoint target mismatch")
    if as_of_date is not None and str(payload["as_of_date"]) != as_of_date:
        raise ValueError("source graph checkpoint as_of mismatch")
    documents = tuple(payload.get("evidence_documents") or ())
    document_ids = [
        str(row.get("document_id") or row.get("source_id") or "")
        for row in documents
    ]
    if any(not value for value in document_ids) or len(document_ids) != len(
        set(document_ids)
    ):
        raise ValueError("source graph document ids must be unique and non-empty")
    validated_quarantined_document_ids(payload)
    query_ids = [
        str(row.get("query_id") or "")
        for row in payload.get("generated_queries") or ()
    ]
    if any(not value for value in query_ids) or len(query_ids) != len(set(query_ids)):
        raise ValueError("source graph query ids must be unique and non-empty")
    for row in documents:
        if row.get("target_id") not in {None, "", payload["target_id"]}:
            raise ValueError("cross-target document found in source graph checkpoint")
        observed = str(
            row.get("published_at")
            or row.get("publication_date")
            or row.get("observed_at")
            or ""
        )[:10]
        if observed and date.fromisoformat(observed) > cutoff:
            raise ValueError("future document found in source graph checkpoint")
    return payload


def validated_quarantined_document_ids(
    checkpoint: Mapping[str, Any],
) -> frozenset[str]:
    """Validate explicit evidence demotion without erasing document lineage."""

    active_ids = {
        str(row.get("document_id") or row.get("source_id") or "")
        for row in checkpoint.get("evidence_documents") or ()
        if str(row.get("document_id") or row.get("source_id") or "")
    }
    rows = tuple(checkpoint.get("quarantined_documents") or ())
    ids = [str(row.get("document_id") or "").strip() for row in rows]
    if any(not value for value in ids) or len(ids) != len(set(ids)):
        raise ValueError("quarantined source document ids must be unique and non-empty")
    if active_ids & set(ids):
        raise ValueError("quarantined source document cannot remain evidence-active")
    rejections = tuple(checkpoint.get("rejected_documents") or ())
    allowed_reason_prefixes = (
        "UNREADABLE_FULL_DOCUMENT_TEXT:",
        "FACT_EXTRACTOR_REPORTED_UNREADABLE_FULL_DOCUMENT",
        "INCOMPLETE_FULL_DOCUMENT_TEXT:",
        "STALE_PDF_READING_ORDER:",
        "STALE_PUBLICATION_DATE_INFERENCE:",
        "NAVIGATION_ONLY_REFERENCE_URL:",
    )
    for row in rows:
        document_id = str(row.get("document_id") or "").strip()
        candidate_id = str(row.get("candidate_id") or "").strip()
        content_hash = str(row.get("content_hash") or "").strip()
        url = str(row.get("url") or "").strip()
        reason = str(row.get("quarantine_reason") or "").strip()
        if (
            row.get("schema_version") != "e2r_v5_source_graph_quarantine_v1"
            or not candidate_id
            or not re.fullmatch(r"[0-9a-f]{64}", content_hash)
            or not _is_http_url(url)
            or not reason.startswith(allowed_reason_prefixes)
            or row.get("evidence_eligible") is not False
            or row.get("score_authority") is not False
        ):
            raise ValueError("invalid quarantined source document lineage")
        matching_rejections = tuple(
            rejection
            for rejection in rejections
            if str(rejection.get("document_id") or "") == document_id
            and str(rejection.get("candidate_id") or "") == candidate_id
            and str(rejection.get("content_hash") or "") == content_hash
            and str(rejection.get("rejection_reason") or "") == reason
        )
        repair_refetch_required = reason.startswith(
            (
                "INCOMPLETE_FULL_DOCUMENT_TEXT:",
                "STALE_PDF_READING_ORDER:",
                "STALE_PUBLICATION_DATE_INFERENCE:",
            )
        )
        if not matching_rejections or any(
            rejection.get("accepted_claim_ids")
            or rejection.get("retryable") is not repair_refetch_required
            or rejection.get("evidence_eligible") is not False
            or rejection.get("score_authority") is not False
            for rejection in matching_rejections
        ):
            raise ValueError("quarantined source document lacks matching rejection")
    return frozenset(ids)


def _objective_dict(
    row: SourceResearchObjective | Mapping[str, Any],
) -> Mapping[str, Any]:
    if isinstance(row, SourceResearchObjective):
        return row.to_dict()
    preferred = tuple(
        dict.fromkeys(
            family
            for value in row.get("preferred_source_families") or ()
            for family in (_canonical_source_family(str(value)),)
            if family is not None
        )
    )
    objective = SourceResearchObjective(
        objective_id=str(row.get("objective_id") or ""),
        component_id=str(row.get("component_id") or ""),
        research_objective=str(row.get("research_objective") or ""),
        preferred_source_families=preferred,
        counter_or_supersession_required=bool(
            row.get("counter_or_supersession_required", True)
        ),
    )
    if not objective.objective_id or not objective.component_id or not objective.research_objective:
        raise ValueError("source research objective is incomplete")
    unknown = set(objective.preferred_source_families) - set(
        CANONICAL_SOURCE_FAMILIES
    )
    if unknown:
        raise ValueError(f"source objective has unknown families: {sorted(unknown)}")
    return objective.to_dict()


def _fact_dict(row: EvidenceFact | Mapping[str, Any]) -> Mapping[str, Any]:
    return row.to_dict() if isinstance(row, EvidenceFact) else dict(row)


def _validated_pending_query_generation_replay_context(
    state: Mapping[str, Any],
    *,
    objective_ids: frozenset[str],
) -> Mapping[str, Any] | None:
    """Return the semantic input frozen at an unfinished planner call.

    The collaboration provider is asynchronous: the first call persists an
    exact request and returns ``PENDING``.  A downstream memo refresh can then
    temporarily hide the Supervisor gap before the response is imported.  The
    source checkpoint, not that temporary downstream projection, owns the
    unfinished planner handoff.
    """

    raw = state.get("pending_query_generation_replay_context")
    if raw is None:
        return None
    if not isinstance(raw, Mapping):
        raise ValueError("pending query generation replay context must be an object")
    if str(state.get("status") or "") != "QUERY_GENERATION_PENDING":
        return None
    if raw.get("schema_version") != (
        QUERY_GENERATION_REPLAY_CONTEXT_SCHEMA_VERSION
    ):
        raise ValueError("pending query generation replay context schema mismatch")
    if (
        raw.get("transport_state_only") is not True
        or raw.get("originated_from_collaboration_transport_wait") is not True
        or raw.get("query_generation_owner")
        != "SOURCE_QUERY_GENERATION_LLM"
        or raw.get("deterministic_fallback_query_allowed") is not False
        or raw.get("production_score_authority") is not False
    ):
        raise ValueError("pending query generation replay context authority mismatch")
    unresolved = tuple(
        str(value)
        for value in raw.get("unresolved_objective_ids") or ()
        if str(value)
    )
    if not unresolved or len(unresolved) != len(set(unresolved)):
        raise ValueError("pending query generation replay objectives are invalid")
    if not set(unresolved).issubset(objective_ids):
        raise ValueError("pending query generation replay objective is unknown")
    score_gap_context = raw.get("score_gap_context")
    if not isinstance(score_gap_context, Mapping):
        raise ValueError("pending query generation replay gap context is invalid")
    prompt_hash = str(raw.get("prompt_hash") or "")
    origin_prompt_hash = str(raw.get("origin_prompt_hash") or "")
    replay_phase = str(raw.get("replay_phase") or "")
    history = tuple(state.get("query_generation_history") or ())
    latest = history[-1] if history else None
    if (
        not prompt_hash.startswith("QUERYPROMPT-")
        or not origin_prompt_hash.startswith("QUERYPROMPT-")
        or replay_phase
        not in {
            "AWAITING_COLLABORATION_RESPONSE",
            "POST_RESPONSE_SEMANTIC_RETRY",
        }
        or not isinstance(latest, Mapping)
        or str(latest.get("status") or "") != "PENDING"
        or str(latest.get("prompt_hash") or "") != prompt_hash
        or latest.get("queries")
        or (
            replay_phase == "AWAITING_COLLABORATION_RESPONSE"
            and not _query_generation_has_collaboration_transport_wait(latest)
        )
    ):
        raise ValueError("pending query generation replay lineage mismatch")
    return {
        **dict(raw),
        "unresolved_objective_ids": unresolved,
        "score_gap_context": dict(score_gap_context),
    }


def _query_generation_has_collaboration_transport_wait(
    value: Mapping[str, Any],
) -> bool:
    return any(
        re.search(
            r"COLLABORATION_RESPONSE_PENDING:COLLABREQ-[0-9a-f]{64}(?:$|:)",
            str(reason or "").strip(),
        )
        is not None
        for reason in value.get("feedback_for_next_llm_call") or ()
    )


def _candidate_ranking_collaboration_request_ids(
    ranking: CandidateRankingResult,
) -> tuple[str, ...]:
    return tuple(
        dict.fromkeys(
            match.group(1)
            for reason in ranking.pending_reasons
            for match in re.finditer(
                r"(?:^|:)COLLABORATION_RESPONSE_PENDING:"
                r"(COLLABREQ-[0-9a-f]{64})(?=$|:)",
                str(reason or ""),
            )
        )
    )


def _validated_pending_candidate_ranking_replay_context(
    state: Mapping[str, Any],
    *,
    candidates: Sequence[Mapping[str, Any]],
    objective_by_id: Mapping[str, Mapping[str, Any]],
    evidence_documents: Sequence[Mapping[str, Any]],
) -> Mapping[str, Any] | None:
    """Validate one exact asynchronous ranking-to-fetch transport handoff."""

    raw = state.get("pending_candidate_ranking_replay_context")
    if raw is None:
        return None
    if not isinstance(raw, Mapping):
        raise ValueError(
            "pending candidate ranking replay context must be an object"
        )
    if str(state.get("status") or "") not in {
        "CANDIDATE_RANKING_PENDING",
        "CHECKPOINT_PENDING",
        "SOURCE_PROVIDER_PENDING",
    }:
        raise ValueError(
            "pending candidate ranking replay context status mismatch"
        )
    raw_schema_version = str(raw.get("schema_version") or "")
    if raw_schema_version not in {
        CANDIDATE_RANKING_REPLAY_CONTEXT_SCHEMA_VERSION,
        LEGACY_CANDIDATE_RANKING_REPLAY_CONTEXT_SCHEMA_VERSION,
    }:
        raise ValueError(
            "pending candidate ranking replay context schema mismatch"
        )
    if (
        raw.get("transport_state_only") is not True
        or raw.get("originated_from_collaboration_transport_wait") is not True
        or raw.get("candidate_ranking_owner")
        != "SOURCE_CANDIDATE_RANKING_LLM"
        or raw.get("deterministic_fallback_query_allowed") is not False
        or raw.get("production_score_authority") is not False
    ):
        raise ValueError(
            "pending candidate ranking replay context authority mismatch"
        )
    rank_batch_candidate_ids = tuple(
        str(value)
        for value in raw.get("rank_batch_candidate_ids") or ()
        if str(value)
    )
    objective_ids = tuple(
        str(value)
        for value in raw.get("objective_ids") or ()
        if str(value)
    )
    if (
        not rank_batch_candidate_ids
        or len(rank_batch_candidate_ids)
        != len(set(rank_batch_candidate_ids))
        or not objective_ids
        or len(objective_ids) != len(set(objective_ids))
    ):
        raise ValueError(
            "pending candidate ranking replay roster is invalid"
        )
    candidate_by_id = {
        str(row.get("candidate_id") or ""): row
        for row in candidates
        if str(row.get("candidate_id") or "")
    }
    if not set(rank_batch_candidate_ids).issubset(candidate_by_id):
        raise ValueError(
            "pending candidate ranking replay candidate is missing"
        )
    for candidate_id in rank_batch_candidate_ids:
        candidate = candidate_by_id[candidate_id]
        normalized_url = _normalize_url(str(candidate.get("url") or ""))
        if (
            not normalized_url
            or normalized_url
            != str(candidate.get("normalized_url") or "")
            or stable_intelligence_id(
                "SGCAND",
                {
                    "target_id": str(candidate.get("target_id") or ""),
                    "as_of_date": str(candidate.get("as_of_date") or ""),
                    "normalized_url": normalized_url,
                },
            )
            != candidate_id
        ):
            raise ValueError(
                "pending candidate ranking replay candidate identity mismatch"
            )
    if not set(objective_ids).issubset(objective_by_id):
        raise ValueError(
            "pending candidate ranking replay objective is unknown"
        )
    candidate_objective_ids = {
        str(value)
        for candidate_id in rank_batch_candidate_ids
        for value in candidate_by_id[candidate_id].get("objective_ids") or ()
        if str(value)
    }
    if candidate_objective_ids != set(objective_ids):
        raise ValueError(
            "pending candidate ranking replay objective lineage mismatch"
        )
    prompt_hash = str(raw.get("prompt_hash") or "")
    origin_prompt_hash = str(raw.get("origin_prompt_hash") or "")
    prompt_hash_lineage = tuple(
        str(value)
        for value in raw.get("prompt_hash_lineage") or ()
        if str(value)
    )
    collaboration_request_ids = tuple(
        str(value)
        for value in raw.get("collaboration_request_ids") or ()
        if str(value)
    )
    if (
        not prompt_hash.startswith("RANKPROMPT")
        or not origin_prompt_hash.startswith("RANKPROMPT")
        or not prompt_hash_lineage
        or prompt_hash_lineage[0] != origin_prompt_hash
        or prompt_hash not in prompt_hash_lineage
        or len(prompt_hash_lineage) != len(set(prompt_hash_lineage))
        or not collaboration_request_ids
        or len(collaboration_request_ids)
        != len(set(collaboration_request_ids))
        or any(
            re.fullmatch(r"COLLABREQ-[0-9a-f]{64}", value) is None
            for value in collaboration_request_ids
        )
    ):
        raise ValueError(
            "pending candidate ranking replay prompt lineage mismatch"
        )
    replay_phase = str(raw.get("replay_phase") or "")
    fetch_handoff_candidate_ids = tuple(
        str(value)
        for value in raw.get("fetch_handoff_candidate_ids") or ()
        if str(value)
    )
    if replay_phase == "AWAITING_COLLABORATION_RESPONSE":
        if fetch_handoff_candidate_ids or any(
            candidate_by_id[candidate_id].get("ranking_status")
            != "PENDING"
            for candidate_id in rank_batch_candidate_ids
        ):
            raise ValueError(
                "pending candidate ranking replay batch state mismatch"
            )
        current_rank_batch = tuple(
            candidate_by_id[candidate_id]
            for candidate_id in rank_batch_candidate_ids
        )
        current_candidate_prompt_projection_hash = stable_intelligence_id(
            "RANKCANDIDATEPROMPT",
            project_candidate_ranking_discovery_candidates(
                _candidate_ranking_transport_rows(
                    current_rank_batch,
                    evidence_documents=evidence_documents,
                )
            ),
        )
        current_objective_scope_hash = stable_intelligence_id(
            "RANKOBJECTIVES",
            [objective_by_id[objective_id] for objective_id in objective_ids],
        )
        if str(raw.get("objective_scope_hash") or "") != (
            current_objective_scope_hash
        ):
            raise ValueError(
                "pending candidate ranking replay input hash mismatch"
            )
        if (
            raw_schema_version
            == CANDIDATE_RANKING_REPLAY_CONTEXT_SCHEMA_VERSION
            and str(raw.get("candidate_prompt_projection_hash") or "")
            != current_candidate_prompt_projection_hash
        ):
            raise ValueError(
                "pending candidate ranking replay input hash mismatch"
            )
    elif replay_phase == "FETCH_HANDOFF_PENDING":
        if (
            not fetch_handoff_candidate_ids
            or len(fetch_handoff_candidate_ids)
            != len(set(fetch_handoff_candidate_ids))
            or not set(fetch_handoff_candidate_ids).issubset(
                rank_batch_candidate_ids
            )
            or any(
                candidate_by_id[candidate_id].get("ranking_status")
                != "MATERIAL"
                or candidate_by_id[candidate_id].get("fetch_status")
                not in {
                    "MATERIAL_PENDING_FETCH",
                    "FETCH_RETRY_PENDING",
                }
                for candidate_id in fetch_handoff_candidate_ids
            )
        ):
            raise ValueError(
                "pending candidate ranking fetch handoff mismatch"
            )
    else:
        raise ValueError(
            "pending candidate ranking replay phase is invalid"
        )
    validated = {
        **dict(raw),
        "schema_version": CANDIDATE_RANKING_REPLAY_CONTEXT_SCHEMA_VERSION,
        "candidate_prompt_projection_hash": (
            current_candidate_prompt_projection_hash
            if replay_phase == "AWAITING_COLLABORATION_RESPONSE"
            else raw.get("candidate_prompt_projection_hash")
        ),
        "rank_batch_candidate_ids": rank_batch_candidate_ids,
        "objective_ids": objective_ids,
        "prompt_hash_lineage": prompt_hash_lineage,
        "collaboration_request_ids": collaboration_request_ids,
        "fetch_handoff_candidate_ids": fetch_handoff_candidate_ids,
        "replay_phase": replay_phase,
    }
    if (
        raw_schema_version
        == LEGACY_CANDIDATE_RANKING_REPLAY_CONTEXT_SCHEMA_VERSION
    ):
        validated["legacy_schema_migrated_from"] = raw_schema_version
    return validated


