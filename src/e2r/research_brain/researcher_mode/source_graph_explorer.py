def _classify_source_family(
    candidate: Mapping[str, Any], *, url: str, official_hosts: set[str]
) -> str:
    host = _normalized_host(url)
    if "dart.fss.or.kr" in host:
        return "OPENDART"
    if "kind.krx.co.kr" in host or host.endswith("krx.co.kr"):
        return "KIND_KRX"
    if _host_is_official(host, official_hosts):
        return "ISSUER_NEWSROOM"
    if "reuters.com" in host:
        return "REUTERS"
    if candidate.get("is_report_domain") or candidate.get("is_pdf"):
        return "PUBLIC_BROKER_PDF"
    if candidate.get("is_news"):
        return "TRUSTED_BUSINESS_MEDIA"
    return "GENERAL_WEB_DISCOVERY"


def _host_is_official(host: str, official_hosts: set[str]) -> bool:
    return any(
        host == official_host or host.endswith("." + official_host)
        for official_host in official_hosts
        if official_host
    )


def _annotate_candidate_source_hints(
    candidates: Sequence[dict[str, Any]],
    *,
    official_hosts: set[str],
) -> None:
    for candidate in candidates:
        url = str(candidate.get("url") or "")
        host = _normalized_host(url)
        candidate["verified_official_domain_candidate"] = _host_is_official(
            host,
            official_hosts,
        )
        candidate["candidate_source_family_hint"] = _classify_source_family(
            candidate,
            url=url,
            official_hosts=official_hosts,
        )


def _candidate_scope_is_fully_resolved(
    candidate: Mapping[str, Any],
    resolved_objective_ids: set[str],
) -> bool:
    """Keep historical candidate state without blocking unrelated open work."""

    candidate_objective_ids = {
        str(value)
        for value in candidate.get("objective_ids") or ()
        if str(value).strip()
    }
    return candidate_objective_ids.issubset(resolved_objective_ids)


def _candidate_reference_expansion_authority(
    candidate: Mapping[str, Any],
) -> bool:
    return bool(candidate.get("verified_official_domain_candidate")) or str(
        candidate.get("candidate_source_family_hint") or ""
    ) in SOURCE_FAMILY_CLASSES["OFFICIAL"]


def _pending_material_fetch_priority(
    candidate: Mapping[str, Any],
    *,
    as_of_date: date,
    official_first_required: bool,
) -> tuple[Any, ...]:
    """Order a bounded fetch queue without dropping lower-ranked candidates.

    An append-only candidate ledger can contain years of equally material
    documents.  LLM material scores alone then let an older 1.00 candidate
    repeatedly sit ahead of a current 0.99 issuer original.  Production daily
    is official-first, so authority and direct-document routes come first;
    within that generic lane, the latest period available by ``as_of_date``
    comes before the LLM material score.  No company, sector, archetype, or
    missing-slot identifier participates in this ordering.
    """

    material_priority = -float(candidate.get("material_priority") or 0.0)
    candidate_id = str(candidate.get("candidate_id") or "")
    if not official_first_required:
        return (0, 0, 0, 0, material_priority, candidate_id)

    url = str(candidate.get("url") or "")
    content_type = str(candidate.get("content_type") or "").casefold()
    path = urlsplit(url).path.casefold()
    direct_document = (
        "pdf" in content_type
        or path.endswith(
            (
                ".pdf",
                ".doc",
                ".docx",
                ".xls",
                ".xlsx",
                ".ppt",
                ".pptx",
            )
        )
    )
    return (
        0 if _candidate_reference_expansion_authority(candidate) else 1,
        # A parser-semantics retry exists only because this exact material URL
        # was terminal under an older local parser.  Close that finite repair
        # before spending the same bounded epoch on unrelated backlog.
        0 if candidate.get("fetch_semantics_retry_reason") else 1,
        0 if direct_document else 1,
        -_candidate_reference_period_ordinal(
            candidate,
            as_of_date=as_of_date,
        ),
        material_priority,
        candidate_id,
    )


def _ordered_reference_urls(
    values: Sequence[Any],
    *,
    parent_url: str,
) -> tuple[str, ...]:
    """Prioritize document and delegated routes without dropping any link."""

    unique = tuple(
        dict.fromkeys(str(value).strip() for value in values if str(value).strip())
    )
    parent_host = _normalized_host(parent_url)

    def priority(item: tuple[int, str]) -> tuple[int, int]:
        index, url = item
        parts = urlsplit(url)
        if parts.path.casefold().endswith(".pdf"):
            return (0, index)
        host = _normalized_host(url)
        if host and parent_host and host != parent_host:
            return (1, index)
        return (2, index)

    return tuple(url for _, url in sorted(enumerate(unique), key=priority))


def _ordered_candidate_reference_parents(
    candidates: Sequence[Mapping[str, Any]],
    *,
    as_of_date: date,
) -> tuple[Mapping[str, Any], ...]:
    """Prioritize current official reference routes across resumed checkpoints.

    Candidate ledgers are append-only, so insertion order increasingly favors
    old landing pages.  When each checkpoint can transport only a bounded
    number of newly discovered links, a current transcript parent must not sit
    behind years of older event pages.  The ordering uses only generic source
    metadata/URL periods and material priority; it never names a company,
    sector, archetype, or missing score slot, and it drops no parent.
    """

    def priority(candidate: Mapping[str, Any]) -> tuple[Any, ...]:
        has_references = bool(candidate.get("discovered_referenced_urls"))
        return (
            0 if has_references else 1,
            -_candidate_reference_period_ordinal(
                candidate,
                as_of_date=as_of_date,
            ),
            -float(candidate.get("material_priority") or 0.0),
            str(candidate.get("candidate_id") or ""),
        )

    return tuple(sorted(candidates, key=priority))


def _candidate_reference_period_ordinal(
    candidate: Mapping[str, Any],
    *,
    as_of_date: date,
) -> int:
    discovered_references = tuple(
        str(value)
        for value in candidate.get("discovered_referenced_urls") or ()
        if str(value).strip()
    )
    explicit = _parse_date(candidate.get("published_at"))
    inferred = infer_publication_date(
        explicit=explicit,
        metadata_parts=(
            str(candidate.get("url") or ""),
            str(candidate.get("title") or ""),
            *discovered_references,
        ),
        as_of_date=as_of_date,
    )
    if inferred is not None and inferred <= as_of_date:
        return inferred.year * 12 + inferred.month

    metadata = " ".join(
        (
            str(candidate.get("url") or ""),
            str(candidate.get("title") or ""),
            *discovered_references,
        )
    )
    matches = []
    patterns = (
        r"(?i)(?<!\d)(20\d{2})[\s_./-]*Q([1-4])(?!\d)",
        r"(?i)(?<!\d)(20\d{2})[\s_./-]*([1-4])Q(?!\d)",
        r"(?i)(?<!\d)Q([1-4])[\s_./-]*(20\d{2})(?!\d)",
        r"(?<!\d)(20\d{2})\s*년\s*([1-4])\s*분기",
    )
    for pattern in patterns:
        for match in re.finditer(pattern, metadata):
            first, second = map(int, match.groups())
            if first in {1, 2, 3, 4} and second >= 2000:
                quarter, year = first, second
            else:
                year, quarter = first, second
            if year > as_of_date.year:
                continue
            if year == as_of_date.year and quarter > (as_of_date.month - 1) // 3 + 1:
                continue
            matches.append(year * 4 + quarter)
    if matches:
        # Month-scale ordinals keep full dates and quarter metadata comparable.
        quarter_ordinal = max(matches)
        year, quarter = divmod(quarter_ordinal - 1, 4)
        return year * 12 + quarter * 3 + 1
    return 0


def _close_non_authority_candidate_reference_routes(
    candidates: Sequence[dict[str, Any]],
) -> int:
    """Close menu/link discoveries whose fetched parent is not authoritative.

    Direct search results and links explicitly cited by accepted documents are
    untouched.  This only migrates pure page-link candidates such as portal
    navigation that an older checkpoint may already contain.
    """

    by_id = {
        str(row.get("candidate_id") or ""): row
        for row in candidates
        if row.get("candidate_id")
    }
    closed = 0
    for candidate in candidates:
        if not candidate.get("reference_discovery_only"):
            continue
        if candidate.get("direct_search_discovery"):
            continue
        if candidate.get("graph_expansion_parent_document_ids"):
            continue
        parent_ids = tuple(
            str(value)
            for value in candidate.get(
                "graph_expansion_parent_candidate_ids"
            ) or ()
            if str(value).strip()
        )
        if not parent_ids:
            continue
        parents = tuple(by_id[value] for value in parent_ids if value in by_id)
        if any(_candidate_reference_expansion_authority(row) for row in parents):
            continue
        if candidate.get("ranking_status") != "PENDING":
            continue
        candidate["ranking_status"] = "NOT_MATERIAL"
        candidate["fetch_status"] = (
            "REFERENCE_DISCOVERY_REJECTED_UNVERIFIED_PARENT"
        )
        candidate["reference_expansion_rejection_reason"] = (
            "PARENT_PAGE_NOT_VERIFIED_OFFICIAL_SOURCE_ROUTE"
        )
        candidate["reference_expansion_parent_authority_verified"] = False
        closed += 1
    return closed


def _reopen_authority_link_extraction_candidates(
    candidates: Sequence[dict[str, Any]],
    *,
    rejected_documents: Sequence[Mapping[str, Any]],
) -> int:
    """Retry old empty-HTML failures once under link-preserving fetch semantics."""

    empty_html_candidate_ids = {
        str(row.get("candidate_id") or "")
        for row in rejected_documents
        if "live_fetch_unreadable_text:empty_extracted_text"
        in str(row.get("rejection_reason") or "")
    }
    reopened = 0
    for candidate in candidates:
        candidate_id = str(candidate.get("candidate_id") or "")
        if candidate_id not in empty_html_candidate_ids:
            continue
        if not _candidate_reference_expansion_authority(candidate):
            continue
        if candidate.get("ranking_status") != "MATERIAL":
            continue
        if candidate.get("fetch_status") != "FETCH_REJECTED":
            continue
        if candidate.get("discovered_referenced_urls"):
            continue
        if candidate.get("link_preserving_fetch_retry_attempted"):
            continue
        candidate["fetch_status"] = "MATERIAL_PENDING_FETCH"
        candidate["link_preserving_fetch_retry_attempted"] = True
        candidate["link_preserving_fetch_retry_reason"] = (
            "PRIOR_EMPTY_HTML_FETCH_PRECEDED_REFERENCE_PRESERVATION"
        )
        candidate["link_preserving_fetch_policy_version"] = (
            "e2r_v5_verified_authority_link_preservation_v1"
        )
        reopened += 1
    return reopened


def _reopen_fetch_semantics_candidates(
    candidates: Sequence[dict[str, Any]],
    *,
    rejected_documents: Sequence[Mapping[str, Any]],
) -> int:
    """Retry one terminal fetch after a local parser semantics improvement.

    Old checkpoints correctly made an unknown publication date or unreadable
    PDF terminal under the capabilities available at that time.  New generic
    HTML publication metadata and the pdfplumber fallback can change that local
    result without changing the URL.  Each policy gets one auditable retry;
    an identical outcome remains terminal and cannot create an infinite loop.
    """

    latest_reason_by_candidate: dict[str, str] = {}
    for row in rejected_documents:
        candidate_id = str(row.get("candidate_id") or "")
        reason = str(row.get("rejection_reason") or "")
        if candidate_id and reason:
            latest_reason_by_candidate[candidate_id] = reason
    reopened = 0
    for candidate in candidates:
        candidate_id = str(candidate.get("candidate_id") or "")
        reason = latest_reason_by_candidate.get(candidate_id, "")
        if candidate.get("ranking_status") != "MATERIAL":
            continue
        if candidate.get("fetch_status") not in {
            "FETCH_REJECTED",
            "FETCH_ROUTE_EXHAUSTED",
        }:
            continue
        if reason == "UNKNOWN_PUBLISHED_DATE_AFTER_FULL_FETCH":
            flag = "publication_metadata_fetch_retry_attempted"
            if candidate.get(flag):
                continue
            candidate[flag] = True
            candidate["fetch_semantics_retry_reason"] = (
                "PRIOR_UNKNOWN_DATE_PRECEDED_HTML_PUBLICATION_METADATA"
            )
            candidate["fetch_semantics_policy_version"] = (
                PUBLICATION_METADATA_SEMANTICS_VERSION
            )
        elif "live_pdf_text_extraction_failed:" in reason:
            flag = "pdf_fallback_fetch_retry_attempted"
            if candidate.get(flag):
                continue
            candidate[flag] = True
            candidate["fetch_semantics_retry_reason"] = (
                "PRIOR_PDF_FAILURE_PRECEDED_PDFPLUMBER_FALLBACK"
            )
            candidate["fetch_semantics_policy_version"] = (
                "e2r_pdf_text_fallback_v1"
            )
        else:
            continue
        candidate["fetch_status"] = "MATERIAL_PENDING_FETCH"
        reopened += 1
    return reopened


def _source_independence_group(url: str, source_family: str) -> str:
    return f"{source_family}:{_normalized_host(url) or 'unknown'}"


def _document_mentions_target_v5(
    text: str,
    *,
    target_id: str,
    target_name: str,
    target_aliases: Sequence[str],
) -> bool:
    normalized_text = re.sub(r"\s+", "", text).casefold()
    terms = tuple(
        dict.fromkeys(
            re.sub(r"\s+", "", str(value)).casefold()
            for value in (target_name, target_id, *target_aliases)
            if len(re.sub(r"\s+", "", str(value))) >= 3
        )
    )
    return bool(terms and any(term in normalized_text for term in terms))


def _retryable_fetch_reason(reason: str) -> bool:
    lowered = reason.casefold()
    return any(
        token in lowered
        for token in ("timeout", "tempor", "connection", "urlerror", "429", "503")
    )


def _dedupe_mapping_rows(
    rows: Sequence[Mapping[str, Any]], *, key_fields: Sequence[str]
) -> list[dict[str, Any]]:
    result: dict[tuple[str, ...], dict[str, Any]] = {}
    for row in rows:
        key = tuple(str(row.get(field) or "") for field in key_fields)
        result[key] = dict(row)
    return list(result.values())


def _parse_date(value: Any) -> date | None:
    if value is None or value == "":
        return None
    try:
        return date.fromisoformat(str(value)[:10])
    except ValueError:
        return None


def _is_http_url(value: str) -> bool:
    parts = urlsplit(value)
    return parts.scheme in {"http", "https"} and bool(parts.netloc)


def _normalize_url(value: str) -> str:
    if not value:
        return ""
    parts = urlsplit(value.strip())
    host = parts.netloc.casefold()
    path = re.sub(r"/{2,}", "/", parts.path or "/").rstrip("/") or "/"
    query = urlencode(
        sorted(
            (key, item)
            for key, item in parse_qsl(parts.query, keep_blank_values=True)
            if not key.casefold().startswith("utm_")
            and key.casefold() not in {"fbclid", "gclid", "ref", "ocid"}
        )
    )
    return urlunsplit((parts.scheme.casefold(), host, path, query, ""))


def _normalized_host(value: str) -> str:
    candidate = value if "://" in value else "https://" + value
    return urlsplit(candidate).netloc.casefold().split(":", 1)[0].removeprefix("www.")


