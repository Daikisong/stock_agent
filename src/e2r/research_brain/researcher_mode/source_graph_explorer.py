def _resume_acquisition_state(
    checkpoint: Mapping[str, Any], *, target_id: str, as_of_date: str, mode: str
) -> dict[str, Any]:
    if checkpoint.get("checkpoint_hash") != _checkpoint_hash(checkpoint):
        raise ValueError("source graph checkpoint hash mismatch")
    for key, expected in (
        ("target_id", target_id),
        ("as_of_date", as_of_date),
        ("mode", mode),
    ):
        if str(checkpoint.get(key)) != expected:
            raise ValueError(f"source graph checkpoint {key} mismatch")
    state = json.loads(json.dumps(checkpoint, ensure_ascii=False))
    state["resumed_from_checkpoint_id"] = checkpoint.get("checkpoint_id")
    state.pop("checkpoint_id", None)
    state.pop("checkpoint_hash", None)
    return state


def _finalize_checkpoint(state: Mapping[str, Any]) -> Mapping[str, Any]:
    payload = json.loads(json.dumps(state, ensure_ascii=False, default=str))
    payload.pop("checkpoint_id", None)
    payload.pop("checkpoint_hash", None)
    checkpoint_hash = _checkpoint_hash(payload)
    payload["checkpoint_hash"] = checkpoint_hash
    payload["checkpoint_id"] = stable_intelligence_id(
        "SGCHECK",
        {
            "target_id": payload["target_id"],
            "as_of_date": payload["as_of_date"],
            "epoch": payload["epoch"],
            "checkpoint_hash": checkpoint_hash,
        },
    )
    return payload


def _checkpoint_hash(checkpoint: Mapping[str, Any]) -> str:
    payload = {
        key: value
        for key, value in checkpoint.items()
        if key not in {"checkpoint_id", "checkpoint_hash"}
    }
    return hashlib.sha256(
        json.dumps(payload, ensure_ascii=False, sort_keys=True, default=str).encode(
            "utf-8"
        )
    ).hexdigest()


def _merge_official_documents(
    state: dict[str, Any],
    documents: Sequence[Mapping[str, Any]],
    *,
    target_id: str,
    as_of_date: str,
) -> None:
    existing = {
        str(row.get("document_id")): row for row in state["evidence_documents"]
    }
    cutoff = date.fromisoformat(as_of_date)
    for raw in documents:
        row = dict(raw)
        document_id = str(row.get("document_id") or "").strip()
        if not document_id:
            raise ValueError("official source graph document_id is required")
        if str(row.get("target_id") or target_id) != target_id:
            raise ValueError("official source graph document target mismatch")
        observed = _observed_date(row)
        if observed and observed > cutoff:
            raise ValueError("future official document cannot enter source graph")
        content = str(
            row.get("content_text")
            or row.get("full_text")
            or row.get("content")
            or ""
        )
        if row.get("evidence_eligible", True) and not content.strip():
            raise ValueError("evidence-eligible official document requires full text")
        content_hash = str(row.get("content_hash") or "")
        if content and not content_hash:
            content_hash = hashlib.sha256(content.encode("utf-8")).hexdigest()
        row.update(
            {
                "target_id": target_id,
                "as_of_date": as_of_date,
                "content_text": content,
                "content_hash": content_hash,
                "snippet_only": False,
                "snippet_used_as_document": False,
                "parser_field_direct_score_authority": False,
                "production_score_authority": False,
            }
        )
        if document_id in existing:
            if existing[document_id].get("content_hash") != content_hash:
                raise ValueError("official document identity collision")
            continue
        existing[document_id] = row
        state["evidence_documents"].append(row)


def _validate_provider_mode(
    *,
    config: SourceGraphAcquisitionConfig,
    search_provider: SearchProvider,
    page_fetcher: PageFetcher,
) -> None:
    if config.mode != SourceGraphAcquisitionMode.PRODUCTION_DAILY.value:
        return
    if (
        not isinstance(search_provider, NaverFreeSearchProvider)
        or search_provider.fixture_mode
        or not search_provider.live_enabled
        or search_provider.fixture_provider is not None
    ):
        raise ValueError("production source graph requires live Naver provider")
    if (
        not isinstance(page_fetcher, PageFetcher)
        or not page_fetcher.live_enabled
        or bool(page_fetcher.fixture_text_by_url)
    ):
        raise ValueError("production source graph requires live PageFetcher")
    if page_fetcher.max_text_chars is None:
        raise ValueError(
            "production daily source graph requires a bounded PageFetcher"
        )


def _quarantine_unreadable_documents(
    state: dict[str, Any],
    *,
    parser_repair_document_ids: Sequence[str] = (),
) -> tuple[str, ...]:
    """Remove unreadable or parser-stale documents on checkpoint resume.

    Older checkpoints may contain PDF text that an extractor reported as a
    success even though it consists mostly of control characters.  Keeping the
    row would make every later fact-extraction epoch retry an impossible input.
    The document is therefore removed from evidence authority while its URL,
    content hash, query lineage, and rejection reason remain auditable.
    """

    documents = list(state.get("evidence_documents") or ())
    candidates = list(state.get("search_candidates") or ())
    candidate_by_document_id = {
        str(row.get("document_id") or ""): row
        for row in candidates
        if row.get("document_id")
    }
    candidate_by_url = {
        _normalize_url(str(row.get("url") or "")): row
        for row in candidates
        if row.get("url")
    }
    kept: list[dict[str, Any]] = []
    reasons: list[str] = []
    quarantine_rows = list(state.setdefault("quarantined_documents", []))
    for row in quarantine_rows:
        row.setdefault("target_id", state.get("target_id"))
        row.setdefault("as_of_date", state.get("as_of_date"))
    rejected_rows = state.setdefault("rejected_documents", [])
    query_failures = state.setdefault("query_failures", [])
    parser_repair_ids = {
        str(value).strip()
        for value in parser_repair_document_ids
        if str(value).strip()
    }
    for raw_document in documents:
        document = dict(raw_document)
        content = str(
            document.get("content_text")
            or document.get("full_text")
            or document.get("content")
            or ""
        )
        unreadable = extracted_text_unreadable_reason(content)
        document_id = str(document.get("document_id") or "")
        legacy_text_cap = (
            str(document.get("source_provider") or "") == "PageFetcher"
            and len(content) == 200_000
            and document.get("text_complete") is not True
        )
        document_is_pdf = (
            bool(document.get("is_pdf"))
            or "pdf" in str(document.get("content_type") or "").casefold()
            or urlsplit(
                str(document.get("canonical_url") or document.get("url") or "")
            ).path.casefold().endswith(".pdf")
        )
        stale_pdf_reading_order = (
            document_id in parser_repair_ids
            and document_is_pdf
            and document.get("text_extraction_semantics_version")
            != PDF_TEXT_EXTRACTION_SEMANTICS_VERSION
        )
        if (
            unreadable is None
            and not legacy_text_cap
            and not stale_pdf_reading_order
        ):
            kept.append(document)
            continue
        url = str(document.get("canonical_url") or document.get("url") or "")
        repair_refetch_required = legacy_text_cap or stale_pdf_reading_order
        rejection_reason = (
            "INCOMPLETE_FULL_DOCUMENT_TEXT:LEGACY_PAGE_FETCH_200000_CHAR_CAP"
            if legacy_text_cap
            else "STALE_PDF_READING_ORDER:EXACT_QUOTE_VALIDATION_FAILED"
            if stale_pdf_reading_order
            else f"UNREADABLE_FULL_DOCUMENT_TEXT:{unreadable}"
        )
        candidate = candidate_by_document_id.get(document_id) or candidate_by_url.get(
            _normalize_url(url)
        )
        candidate_payload: Mapping[str, Any] = candidate or {
            "candidate_id": stable_intelligence_id(
                "SGCANDQUARANTINE",
                {
                    "target_id": state.get("target_id"),
                    "as_of_date": state.get("as_of_date"),
                    "document_id": document_id,
                    "url": url,
                },
            ),
            "url": url,
            "query_ids": list(document.get("query_ids") or ()),
            "objective_ids": list(document.get("objective_ids") or ()),
        }
        if candidate is not None:
            candidate["fetch_status"] = (
                "MATERIAL_PENDING_FETCH"
                if repair_refetch_required
                else "FETCH_REJECTED_UNREADABLE_TEXT"
            )
            candidate["last_fetch_failure_reason"] = rejection_reason
            candidate["alternate_route_required"] = not repair_refetch_required
            candidate["quarantined_document_id"] = document_id
            candidate.pop("document_id", None)
            if repair_refetch_required:
                candidate["parser_semantics_refetch_required"] = True
                candidate["parser_semantics_policy_version"] = (
                    PDF_TEXT_EXTRACTION_SEMANTICS_VERSION
                    if stale_pdf_reading_order
                    else TEXT_CACHE_SEMANTICS_VERSION
                )
        rejection = dict(
            _candidate_rejection(
                candidate_payload,
                rejection_reason,
                retryable=repair_refetch_required,
                content_hash=str(document.get("content_hash") or "") or None,
            )
        )
        rejection.update(
            {
                "document_id": document_id,
                "quarantined_on_checkpoint_resume": True,
                "evidence_eligible": False,
                "alternate_route_required": not repair_refetch_required,
                "parser_refetch_required": repair_refetch_required,
            }
        )
        rejected_rows.append(rejection)
        quarantine_rows.append(
            {
                "schema_version": "e2r_v5_source_graph_quarantine_v1",
                "document_id": document_id,
                "target_id": state.get("target_id"),
                "as_of_date": state.get("as_of_date"),
                "candidate_id": candidate_payload.get("candidate_id"),
                "url": url,
                "content_hash": document.get("content_hash"),
                "query_ids": list(document.get("query_ids") or ()),
                "objective_ids": list(document.get("objective_ids") or ()),
                "quarantine_reason": rejection_reason,
                "evidence_eligible": False,
                "score_authority": False,
                "parser_refetch_required": repair_refetch_required,
            }
        )
        query_failures.append(
            {
                "query_id": str(
                    next(iter(document.get("query_ids") or ()), "CHECKPOINT_VALIDATION")
                ),
                "objective_id": str(
                    next(iter(document.get("objective_ids") or ()), "UNKNOWN_OBJECTIVE")
                ),
                "candidate_id": candidate_payload.get("candidate_id"),
                "document_id": document_id,
                "url": url,
                "failure_stage": "FULL_DOCUMENT_READABILITY_VALIDATION",
                "failure_reason": rejection_reason,
                "alternate_route_required": not repair_refetch_required,
                "parser_refetch_required": repair_refetch_required,
            }
        )
        reasons.append(rejection_reason)
    state["evidence_documents"] = kept
    state["quarantined_documents"] = _dedupe_mapping_rows(
        quarantine_rows, key_fields=("document_id", "quarantine_reason")
    )
    return tuple(dict.fromkeys(reasons))


def _quarantine_stale_publication_dates(
    state: dict[str, Any],
) -> tuple[str, ...]:
    """Demote legacy rows whose article date changes under current semantics.

    Some HTML pages split ``입력`` and its timestamp across adjacent text
    nodes while keeping the publisher's old registration date on one line in
    the footer.  Older checkpoints therefore accepted the footer date.  A
    changed date alters both as-of eligibility and relative expressions such
    as "올해/내년", so the old document identity and every derived fact must
    be retired.  The original URL is reopened once and fetched under the new
    semantics; this is a bounded parser repair, not a new LLM query.
    """

    cutoff = date.fromisoformat(str(state.get("as_of_date") or ""))
    documents = list(state.get("evidence_documents") or ())
    candidates = list(state.get("search_candidates") or ())
    candidate_by_document_id = {
        str(row.get("document_id") or ""): row
        for row in candidates
        if row.get("document_id")
    }
    candidate_by_url = {
        _normalize_url(str(row.get("url") or "")): row
        for row in candidates
        if row.get("url")
    }
    kept: list[dict[str, Any]] = []
    reasons: list[str] = []
    quarantine_rows = list(state.setdefault("quarantined_documents", []))
    rejected_rows = state.setdefault("rejected_documents", [])
    query_failures = state.setdefault("query_failures", [])
    for raw_document in documents:
        document = dict(raw_document)
        repair = _repaired_publication_date(document, cutoff=cutoff)
        if repair is None:
            kept.append(document)
            continue
        stored_date, repaired_date = repair
        document_id = str(document.get("document_id") or "")
        url = str(document.get("canonical_url") or document.get("url") or "")
        reason = (
            "STALE_PUBLICATION_DATE_INFERENCE:"
            f"{stored_date.isoformat()}->{repaired_date.isoformat()}"
        )
        candidate = candidate_by_document_id.get(document_id) or candidate_by_url.get(
            _normalize_url(url)
        )
        candidate_payload: Mapping[str, Any] = candidate or {
            "candidate_id": stable_intelligence_id(
                "SGCANDDATEQUARANTINE",
                {
                    "target_id": state.get("target_id"),
                    "as_of_date": state.get("as_of_date"),
                    "document_id": document_id,
                    "url": url,
                },
            ),
            "url": url,
            "query_ids": list(document.get("query_ids") or ()),
            "objective_ids": list(document.get("objective_ids") or ()),
        }
        if candidate is not None:
            candidate["fetch_status"] = "MATERIAL_PENDING_FETCH"
            candidate["last_fetch_failure_reason"] = reason
            candidate["alternate_route_required"] = False
            candidate["quarantined_document_id"] = document_id
            candidate["publication_date_inference_refetch_required"] = True
            candidate["publication_date_inference_policy_version"] = (
                PUBLICATION_DATE_INFERENCE_SEMANTICS_VERSION
            )
            candidate.pop("document_id", None)
        rejection = dict(
            _candidate_rejection(
                candidate_payload,
                reason,
                retryable=True,
                content_hash=str(document.get("content_hash") or "") or None,
            )
        )
        rejection.update(
            {
                "document_id": document_id,
                "quarantined_on_checkpoint_resume": True,
                "evidence_eligible": False,
                "score_authority": False,
                "publication_date_refetch_required": True,
            }
        )
        rejected_rows.append(rejection)
        quarantine_rows.append(
            {
                "schema_version": "e2r_v5_source_graph_quarantine_v1",
                "document_id": document_id,
                "target_id": state.get("target_id"),
                "as_of_date": state.get("as_of_date"),
                "candidate_id": candidate_payload.get("candidate_id"),
                "url": url,
                "content_hash": document.get("content_hash"),
                "query_ids": list(document.get("query_ids") or ()),
                "objective_ids": list(document.get("objective_ids") or ()),
                "quarantine_reason": reason,
                "evidence_eligible": False,
                "score_authority": False,
                "publication_date_refetch_required": True,
                "stored_publication_date": stored_date.isoformat(),
                "repaired_publication_date": repaired_date.isoformat(),
                "publication_date_inference_policy_version": (
                    PUBLICATION_DATE_INFERENCE_SEMANTICS_VERSION
                ),
            }
        )
        query_failures.append(
            {
                "query_id": str(
                    next(iter(document.get("query_ids") or ()), "CHECKPOINT_VALIDATION")
                ),
                "objective_id": str(
                    next(iter(document.get("objective_ids") or ()), "UNKNOWN_OBJECTIVE")
                ),
                "candidate_id": candidate_payload.get("candidate_id"),
                "document_id": document_id,
                "url": url,
                "failure_stage": "PUBLICATION_DATE_VALIDATION",
                "failure_reason": reason,
                "alternate_route_required": False,
                "publication_date_refetch_required": True,
            }
        )
        reasons.append(reason)
    state["evidence_documents"] = kept
    state["quarantined_documents"] = _dedupe_mapping_rows(
        quarantine_rows,
        key_fields=("document_id",),
    )
    return tuple(dict.fromkeys(reasons))


def _repaired_publication_date(
    document: Mapping[str, Any],
    *,
    cutoff: date,
) -> tuple[date, date] | None:
    source = str(document.get("publication_date_source") or "")
    if source not in {
        "DOCUMENT_CONTENT_INFERENCE",
        "HTTP_LAST_MODIFIED_AND_DOCUMENT_INFERENCE_MAX",
    }:
        return None
    stored = _parse_date(document.get("published_at"))
    if stored is None:
        return None
    inferred = infer_publication_date(
        explicit=None,
        metadata_parts=(
            str(document.get("canonical_url") or document.get("url") or ""),
            str(document.get("title") or ""),
            str(document.get("source") or ""),
            *(document.get("publication_metadata_parts") or ()),
        ),
        document_text=str(document.get("content_text") or ""),
        as_of_date=cutoff,
    )
    if source == "HTTP_LAST_MODIFIED_AND_DOCUMENT_INFERENCE_MAX":
        header_date = _parse_date(document.get("response_last_modified_at"))
        values = tuple(value for value in (header_date, inferred) if value is not None)
        inferred = max(values) if values else None
    if inferred is None or inferred == stored:
        return None
    return stored, inferred


def _filter_facts_to_active_source_documents(
    facts: Sequence[Mapping[str, Any]],
    documents: Sequence[Mapping[str, Any]],
) -> tuple[tuple[Mapping[str, Any], ...], int]:
    active_ids = {
        str(row.get("document_id") or "")
        for row in documents
        if str(row.get("document_id") or "")
    }
    kept: list[Mapping[str, Any]] = []
    invalidated = 0
    for row in facts:
        source_document_ids = {
            str(value)
            for value in row.get("source_ids") or ()
            if str(value).startswith("SGDOC-")
        }
        if source_document_ids and not source_document_ids.issubset(active_ids):
            invalidated += 1
            continue
        kept.append(row)
    return tuple(kept), invalidated


def _fact_parser_repair_document_ids(
    score_gap_context: Mapping[str, Any],
) -> tuple[str, ...]:
    """Recover document ids from exact-quote failures, never from gap names."""

    pending: list[Any] = [score_gap_context]
    document_ids: list[str] = []
    pattern = re.compile(
        r"MATERIAL_FACT_PROPOSAL_REJECTED:"
        r"(SGDOC-[0-9a-f]+):EXACT_QUOTE_NOT_IN_FULL_DOCUMENT"
    )
    while pending:
        value = pending.pop()
        if isinstance(value, Mapping):
            pending.extend(value.values())
        elif isinstance(value, (list, tuple, set, frozenset)):
            pending.extend(value)
        elif isinstance(value, str):
            document_ids.extend(pattern.findall(value))
    return tuple(dict.fromkeys(document_ids))


def _execute_search_query(
    *,
    search_provider: SearchProvider,
    query: str,
    query_id: str,
    objective_id: str,
    requested_source_families: Sequence[str],
    target_id: str,
    as_of_date: date,
    max_results: int,
) -> tuple[tuple[Mapping[str, Any], ...], tuple[str, ...]]:
    error_start = len(getattr(search_provider, "errors", ()))
    try:
        results = tuple(search_provider.search(query, as_of_date, max_results))
    except Exception as exc:
        return (), (f"{type(exc).__name__}:{exc}",)
    errors = tuple(
        str(value)
        for value in tuple(getattr(search_provider, "errors", ()))[error_start:]
    )
    rows = []
    for result in results:
        if not isinstance(result, SearchResult):
            raise ValueError("search provider returned non-SearchResult")
        normalized_url = _normalize_url(result.url)
        candidate_id = stable_intelligence_id(
            "SGCAND",
            {
                "target_id": target_id,
                "as_of_date": as_of_date.isoformat(),
                "normalized_url": normalized_url,
            },
        )
        rows.append(
            {
                "schema_version": "e2r_v5_search_candidate_v1",
                "candidate_id": candidate_id,
                "target_id": target_id,
                "as_of_date": as_of_date.isoformat(),
                "url": result.url,
                "normalized_url": normalized_url,
                "title": result.title,
                "snippet": result.snippet,
                "source": result.source,
                "published_at": (
                    result.published_at.isoformat() if result.published_at else None
                ),
                "rank": result.rank,
                "is_pdf": result.is_pdf,
                "is_report_domain": result.is_report_domain,
                "is_news": result.is_news,
                "is_disclosure": result.is_disclosure,
                "query_ids": [query_id],
                "objective_ids": [objective_id],
                "requested_source_families": list(
                    dict.fromkeys(requested_source_families)
                ),
                "direct_search_discovery": True,
                "query_lineage_valid": result.query in {None, query},
                "discovery_only": True,
                "snippet_discovery_only": True,
                "snippet_evidence_eligible": False,
                "score_authority": False,
                "ranking_status": "PENDING",
                "fetch_status": "NOT_STARTED",
            }
        )
    return tuple(rows), errors


def _merge_search_candidates(
    candidates: list[dict[str, Any]],
    rejected: list[dict[str, Any]],
    new_rows: Sequence[Mapping[str, Any]],
    *,
    cutoff: date,
) -> None:
    by_url = {str(row["normalized_url"]): row for row in candidates}
    for raw in new_rows:
        row = dict(raw)
        reason = None
        if not row.get("query_lineage_valid"):
            reason = "QUERY_LINEAGE_MISMATCH"
        elif not _is_http_url(str(row.get("url") or "")):
            reason = "INVALID_OR_NON_HTTP_URL"
        published = _parse_date(row.get("published_at"))
        if published and published > cutoff:
            reason = "FUTURE_SEARCH_RESULT"
        if reason:
            rejected.append(_candidate_rejection(row, reason, retryable=False))
            continue
        key = str(row["normalized_url"])
        existing = by_url.get(key)
        if existing is None:
            candidates.append(row)
            by_url[key] = row
            continue
        existing["query_ids"] = list(
            dict.fromkeys((*existing.get("query_ids", ()), *row.get("query_ids", ())))
        )
        existing["objective_ids"] = list(
            dict.fromkeys(
                (*existing.get("objective_ids", ()), *row.get("objective_ids", ()))
            )
        )
        existing["requested_source_families"] = list(
            dict.fromkeys(
                (
                    *existing.get("requested_source_families", ()),
                    *row.get("requested_source_families", ()),
                )
            )
        )
        existing["direct_search_discovery"] = bool(
            existing.get("direct_search_discovery")
            or row.get("direct_search_discovery")
        )


def _reject_future_candidate_metadata(
    candidates: Sequence[dict[str, Any]],
    rejected: list[dict[str, Any]],
    *,
    cutoff: date,
) -> frozenset[str]:
    """Quarantine future-dated source locators before any LLM sees them.

    Some official systems encode the publication date in a document locator
    while omitting a separate ``published_at`` field.  DART receipt numbers
    are one example.  Such a URL may be discovered from a live landing page
    after the historical ``as_of_date``.  Keep an auditable rejection ledger,
    but never send the candidate to ranking or fetch it as historical evidence.
    """

    rejected_keys = {
        (
            str(row.get("candidate_id") or ""),
            str(row.get("rejection_reason") or ""),
        )
        for row in rejected
    }
    rejected_candidate_ids: set[str] = set()
    for candidate in candidates:
        candidate_id = str(candidate.get("candidate_id") or "").strip()
        if not candidate_id:
            continue
        inferred = (
            _parse_date(candidate.get("published_at"))
            or infer_source_locator_publication_date(
                str(candidate.get("url") or "")
            )
        )
        if inferred is None or inferred <= cutoff:
            continue
        reason = "FUTURE_CANDIDATE_SOURCE_LOCATOR_DATE"
        candidate["published_at"] = inferred.isoformat()
        candidate["publication_date_state"] = (
            "REJECTED_FUTURE_SOURCE_LOCATOR"
        )
        candidate["publication_date_basis"] = (
            "OFFICIAL_SOURCE_LOCATOR_METADATA"
        )
        candidate["future_candidate_rejected_before_llm"] = True
        candidate["ranking_status"] = "REJECTED_FUTURE"
        candidate["fetch_status"] = "FETCH_REJECTED"
        for key in (
            "materiality_decision_id",
            "material_priority",
            "materiality_rationale",
            "document_id",
        ):
            candidate.pop(key, None)
        rejection_key = (candidate_id, reason)
        if rejection_key not in rejected_keys:
            rejection = _candidate_rejection(
                candidate,
                reason,
                retryable=False,
            )
            rejection["inferred_published_at"] = inferred.isoformat()
            rejection["as_of_date"] = cutoff.isoformat()
            rejection["future_candidate_rejected_before_llm"] = True
            rejected.append(rejection)
            rejected_keys.add(rejection_key)
        rejected_candidate_ids.add(candidate_id)
    return frozenset(rejected_candidate_ids)


def _enqueue_reference_candidates(
    candidates: list[dict[str, Any]],
    *,
    document: Mapping[str, Any],
    target_id: str,
    as_of_date: str,
    default_objective_ids: Sequence[str],
    max_total_candidates: int | None = None,
) -> int:
    by_url = {str(row.get("normalized_url")): row for row in candidates}
    deferred_count = 0
    requested_source_families = tuple(
        document.get("requested_source_families") or ()
    )
    document_source_family = str(document.get("source_family") or "")
    document_text = str(
        document.get("content_text")
        or document.get("full_text")
        or document.get("content")
        or ""
    )
    authority_backed_document = (
        document_source_family in SOURCE_FAMILY_CLASSES["OFFICIAL"]
    )
    for raw_url in _ordered_reference_urls(
        document.get("referenced_urls") or (),
        parent_url=str(document.get("canonical_url") or document.get("url") or ""),
    ):
        url = str(raw_url).strip()
        normalized = _normalize_url(url)
        if not normalized or not _is_http_url(url):
            continue
        if not authority_backed_document and url not in document_text:
            # HTML navigation hrefs are stripped from fetched text.  A
            # non-official document can expand only a URL it explicitly cites
            # in its retained body, not every menu/share link on the page.
            continue
        existing = by_url.get(normalized)
        objective_ids = tuple(
            document.get("objective_ids") or default_objective_ids
        )
        query_ids = tuple(document.get("query_ids") or ())
        if existing is not None:
            existing["objective_ids"] = list(
                dict.fromkeys((*existing.get("objective_ids", ()), *objective_ids))
            )
            existing["query_ids"] = list(
                dict.fromkeys((*existing.get("query_ids", ()), *query_ids))
            )
            existing["requested_source_families"] = list(
                dict.fromkeys(
                    (
                        *existing.get("requested_source_families", ()),
                        *requested_source_families,
                    )
                )
            )
            existing["graph_expansion_parent_document_ids"] = list(
                dict.fromkeys(
                    (
                        *existing.get("graph_expansion_parent_document_ids", ()),
                        document.get("document_id"),
                    )
                )
            )
            continue
        if (
            max_total_candidates is not None
            and len(candidates) >= max_total_candidates
        ):
            deferred_count += 1
            continue
        candidate_id = stable_intelligence_id(
            "SGCAND",
            {
                "target_id": target_id,
                "as_of_date": as_of_date,
                "normalized_url": normalized,
            },
        )
        row = {
            "schema_version": "e2r_v5_search_candidate_v1",
            "candidate_id": candidate_id,
            "target_id": target_id,
            "as_of_date": as_of_date,
            "url": url,
            "normalized_url": normalized,
            "title": f"Referenced by {document.get('document_id')}",
            "snippet": None,
            "source": _normalized_host(url),
            "published_at": None,
            "rank": 0,
            "is_pdf": urlsplit(url).path.casefold().endswith(".pdf"),
            "is_report_domain": False,
            "is_news": "news" in _normalized_host(url),
            "is_disclosure": False,
            "query_ids": list(query_ids),
            "objective_ids": list(objective_ids),
            "requested_source_families": list(requested_source_families),
            "query_lineage_valid": True,
            "graph_expansion_parent_document_ids": [document.get("document_id")],
            "discovery_only": True,
            "snippet_discovery_only": True,
            "snippet_evidence_eligible": False,
            "score_authority": False,
            "ranking_status": "PENDING",
            "fetch_status": "NOT_STARTED",
        }
        candidates.append(row)
        by_url[normalized] = row
    return deferred_count


def _enqueue_candidate_discovery_references(
    candidates: list[dict[str, Any]],
    *,
    parent_candidate: Mapping[str, Any],
    target_id: str,
    as_of_date: str,
    max_total_candidates: int | None = None,
) -> int:
    """Keep fetched-page links as discovery even when the page is not evidence.

    An unknown publication date or a tiny JavaScript redirect page must not
    become evidence.  Its explicit links can still be ranked and fully fetched
    on a later checkpoint, preserving the parent candidate lineage.
    """

    parent_id = str(parent_candidate.get("candidate_id") or "").strip()
    if not parent_id:
        return 0
    if not _candidate_reference_expansion_authority(parent_candidate):
        return 0
    parent_url = _normalize_url(str(parent_candidate.get("url") or ""))
    by_url = {str(row.get("normalized_url")): row for row in candidates}
    objective_ids = tuple(parent_candidate.get("objective_ids") or ())
    query_ids = tuple(parent_candidate.get("query_ids") or ())
    requested_source_families = tuple(
        parent_candidate.get("requested_source_families") or ()
    )
    deferred_count = 0
    for raw_url in _ordered_reference_urls(
        parent_candidate.get("discovered_referenced_urls") or (),
        parent_url=str(parent_candidate.get("url") or ""),
    ):
        url = str(raw_url).strip()
        normalized = _normalize_url(url)
        if (
            not normalized
            or normalized == parent_url
            or not _is_http_url(url)
        ):
            continue
        existing = by_url.get(normalized)
        if existing is not None:
            existing["objective_ids"] = list(
                dict.fromkeys((*existing.get("objective_ids", ()), *objective_ids))
            )
            existing["query_ids"] = list(
                dict.fromkeys((*existing.get("query_ids", ()), *query_ids))
            )
            existing["requested_source_families"] = list(
                dict.fromkeys(
                    (
                        *existing.get("requested_source_families", ()),
                        *requested_source_families,
                    )
                )
            )
            existing["graph_expansion_parent_candidate_ids"] = list(
                dict.fromkeys(
                    (
                        *existing.get("graph_expansion_parent_candidate_ids", ()),
                        parent_id,
                    )
                )
            )
            continue
        if (
            max_total_candidates is not None
            and len(candidates) >= max_total_candidates
        ):
            deferred_count += 1
            continue
        candidate_id = stable_intelligence_id(
            "SGCAND",
            {
                "target_id": target_id,
                "as_of_date": as_of_date,
                "normalized_url": normalized,
            },
        )
        row = {
            "schema_version": "e2r_v5_search_candidate_v1",
            "candidate_id": candidate_id,
            "target_id": target_id,
            "as_of_date": as_of_date,
            "url": url,
            "normalized_url": normalized,
            "title": f"Referenced by candidate {parent_id}",
            "snippet": None,
            "source": _normalized_host(url),
            "published_at": None,
            "rank": 0,
            "is_pdf": urlsplit(url).path.casefold().endswith(".pdf"),
            "is_report_domain": False,
            "is_news": "news" in _normalized_host(url),
            "is_disclosure": False,
            "query_ids": list(query_ids),
            "objective_ids": list(objective_ids),
            "requested_source_families": list(requested_source_families),
            "query_lineage_valid": True,
            "graph_expansion_parent_candidate_ids": [parent_id],
            "reference_discovery_only": True,
            "reference_expansion_parent_authority_verified": True,
            "reference_expansion_policy": "VERIFIED_OFFICIAL_PARENT_ONLY",
            "discovery_only": True,
            "snippet_discovery_only": True,
            "snippet_evidence_eligible": False,
            "score_authority": False,
            "ranking_status": "PENDING",
            "fetch_status": "NOT_STARTED",
        }
        candidates.append(row)
        by_url[normalized] = row
    return deferred_count


def _fetch_candidate_document(
    *,
    candidate: dict[str, Any],
    target_id: str,
    target_name: str,
    target_aliases: Sequence[str],
    as_of_date: date,
    page_fetcher: PageFetcher,
    min_chars: int,
    require_date_verified: bool,
    official_hosts: set[str],
    content_hash_to_document: dict[str, Mapping[str, Any]],
) -> tuple[Mapping[str, Any], Mapping[str, Any] | None, Mapping[str, Any] | None]:
    url = str(candidate["url"])
    fetch_id = stable_intelligence_id(
        "SGFETCH",
        {"candidate_id": candidate["candidate_id"], "url": url},
    )
    try:
        result = page_fetcher.fetch(url, as_of_date=as_of_date)
    except Exception as exc:
        reason = f"PAGE_FETCH_PROVIDER_ERROR:{type(exc).__name__}:{exc}"
        rejection = _candidate_rejection(candidate, reason, retryable=True)
        return _fetch_record(fetch_id, candidate, "FETCH_FAILED", reason), None, rejection
    page_referenced_urls = tuple(
        str(value).rstrip(".,);]")
        for value in getattr(result, "referenced_urls", ())
        if str(value).strip()
    )
    candidate["discovered_page_referenced_urls"] = list(
        dict.fromkeys(page_referenced_urls)
    )
    candidate["discovered_text_referenced_urls"] = []
    candidate["discovered_referenced_urls"] = [
        value
        for value in dict.fromkeys(page_referenced_urls)
        if _normalize_url(value) != _normalize_url(url)
    ]
    if not result.ok or not str(result.text or "").strip():
        reason = "SNIPPET_ONLY_FULL_FETCH_REQUIRED:" + str(
            result.reason or "empty full document"
        )
        retryable = _retryable_fetch_reason(reason)
        rejection = _candidate_rejection(candidate, reason, retryable=retryable)
        return _fetch_record(fetch_id, candidate, "FETCH_FAILED", reason), None, rejection
    text = str(result.text or "").strip()
    if getattr(result, "text_complete", True) is not True:
        returned_chars = int(
            getattr(result, "returned_text_chars", None) or len(text)
        )
        original_chars = int(
            getattr(result, "original_text_chars", None) or returned_chars
        )
        reason = (
            "INCOMPLETE_FULL_DOCUMENT_TEXT:"
            f"{returned_chars}/{original_chars}"
        )
        rejection = _candidate_rejection(
            candidate,
            reason,
            retryable=True,
        )
        return (
            _fetch_record(fetch_id, candidate, "FETCH_FAILED", reason),
            None,
            rejection,
        )
    text_referenced_urls = tuple(
        value.rstrip(".,);]")
        for value in re.findall(r"https?://[^\s<>\"']+", text)
    )
    referenced_urls = tuple(
        dict.fromkeys(
            (
                *page_referenced_urls,
                *text_referenced_urls,
            )
        )
    )
    candidate["discovered_page_referenced_urls"] = list(
        dict.fromkeys(page_referenced_urls)
    )
    candidate["discovered_text_referenced_urls"] = list(
        dict.fromkeys(text_referenced_urls)
    )
    candidate["discovered_referenced_urls"] = [
        value
        for value in referenced_urls
        if _normalize_url(value) != _normalize_url(url)
    ]
    content_hash = hashlib.sha256(text.encode("utf-8")).hexdigest()
    unreadable = extracted_text_unreadable_reason(text)
    if unreadable is not None:
        reason = f"UNREADABLE_FULL_DOCUMENT_TEXT:{unreadable}"
        rejection = _candidate_rejection(
            candidate,
            reason,
            retryable=False,
            content_hash=content_hash,
        )
        return (
            _fetch_record(fetch_id, candidate, "REJECTED", reason, content_hash),
            None,
            rejection,
        )
    if len(text) < min_chars:
        reason = "FULL_DOCUMENT_CONTENT_TOO_SMALL"
        rejection = _candidate_rejection(candidate, reason, retryable=False, content_hash=content_hash)
        return _fetch_record(fetch_id, candidate, "REJECTED", reason, content_hash), None, rejection
    explicit = _parse_date(candidate.get("published_at"))
    response_last_modified_at = getattr(
        result,
        "response_last_modified_at",
        None,
    )
    response_last_modified = (
        response_last_modified_at.date()
        if isinstance(response_last_modified_at, datetime)
        else response_last_modified_at
        if isinstance(response_last_modified_at, date)
        else None
    )
    publication_metadata_parts = tuple(
        str(value)
        for value in getattr(result, "publication_metadata_parts", ())
        if str(value).strip()
    )
    publication_metadata_inferred_date = infer_publication_date(
        explicit=None,
        metadata_parts=publication_metadata_parts,
        as_of_date=as_of_date,
    )
    content_inferred_date = infer_publication_date(
        explicit=None,
        metadata_parts=(
            url,
            str(candidate.get("title") or ""),
            str(candidate.get("source") or ""),
            *publication_metadata_parts,
        ),
        document_text=text,
        as_of_date=as_of_date,
    )
    if explicit is not None:
        published = explicit
    elif response_last_modified is not None:
        # Last-Modified is useful for otherwise undated issuer assets, but it
        # must not hide a later date explicitly carried by the URL/title/body.
        # Taking the later verified date is conservative against future leak.
        published = max(
            value
            for value in (response_last_modified, content_inferred_date)
            if value is not None
        )
    else:
        published = content_inferred_date
    if published is None and require_date_verified:
        reason = "UNKNOWN_PUBLISHED_DATE_AFTER_FULL_FETCH"
        rejection = _candidate_rejection(candidate, reason, retryable=False, content_hash=content_hash)
        return _fetch_record(fetch_id, candidate, "REJECTED", reason, content_hash), None, rejection
    if published and published > as_of_date:
        reason = "FUTURE_DOCUMENT_AFTER_FULL_FETCH"
        rejection = _candidate_rejection(candidate, reason, retryable=False, content_hash=content_hash)
        return _fetch_record(fetch_id, candidate, "REJECTED", reason, content_hash), None, rejection
    if not _document_mentions_target_v5(
        text,
        target_id=target_id,
        target_name=target_name,
        target_aliases=target_aliases,
    ):
        reason = "WRONG_SUBJECT_FULL_DOCUMENT"
        rejection = _candidate_rejection(candidate, reason, retryable=False, content_hash=content_hash)
        return _fetch_record(fetch_id, candidate, "REJECTED", reason, content_hash), None, rejection
    source_family = _classify_source_family(
        candidate, url=url, official_hosts=official_hosts
    )
    evidence_reference_urls = tuple(
        dict.fromkeys(
            (
                *text_referenced_urls,
                *(
                    page_referenced_urls
                    if source_family in SOURCE_FAMILY_CLASSES["OFFICIAL"]
                    else ()
                ),
            )
        )
    )
    existing = content_hash_to_document.get(content_hash)
    if existing is not None:
        if isinstance(existing, dict):
            existing["query_ids"] = list(
                dict.fromkeys(
                    (*existing.get("query_ids", ()), *candidate.get("query_ids", ()))
                )
            )
            existing["objective_ids"] = list(
                dict.fromkeys(
                    (
                        *existing.get("objective_ids", ()),
                        *candidate.get("objective_ids", ()),
                    )
                )
            )
            existing["discovery_urls"] = list(
                dict.fromkeys((*existing.get("discovery_urls", ()), url))
            )
            existing["requested_source_families"] = list(
                dict.fromkeys(
                    (
                        *existing.get("requested_source_families", ()),
                        *candidate.get("requested_source_families", ()),
                    )
                )
            )
            existing["referenced_urls"] = list(
                dict.fromkeys(
                    (
                        *existing.get("referenced_urls", ()),
                        *evidence_reference_urls,
                    )
                )
            )
            existing_family = str(existing.get("source_family") or "")
            existing["source_family_observations"] = list(
                dict.fromkeys(
                    (
                        *existing.get(
                            "source_family_observations",
                            (existing_family,) if existing_family else (),
                        ),
                        source_family,
                    )
                )
            )
            if source_family in SOURCE_FAMILY_CLASSES["OFFICIAL"]:
                existing["verified_official_discovery_urls"] = list(
                    dict.fromkeys(
                        (
                            *existing.get("verified_official_discovery_urls", ()),
                            url,
                        )
                    )
                )
                if existing_family not in SOURCE_FAMILY_CLASSES["OFFICIAL"]:
                    # The bytes remain one economic document, but a successful
                    # fetch from a verified issuer route upgrades provenance.
                    # This is source verification, not duplicate score credit.
                    existing["source_family_before_official_verification"] = (
                        existing_family or None
                    )
                    existing["source_family"] = source_family
                    existing["canonical_url"] = url
                    existing["source_independence_group"] = (
                        _source_independence_group(url, source_family)
                    )
                    existing["official_provenance_upgrade"] = True
        record = _fetch_record(
            fetch_id,
            candidate,
            "DUPLICATE_CONTENT",
            None,
            content_hash,
        )
        record["existing_document_id"] = existing.get("document_id")
        return record, existing, None
    publication_date_source = (
        "SEARCH_RESULT"
        if explicit is not None
        else "HTTP_LAST_MODIFIED_AND_DOCUMENT_INFERENCE_MAX"
        if (
            response_last_modified is not None
            and content_inferred_date is not None
            and content_inferred_date != response_last_modified
        )
        else "HTTP_LAST_MODIFIED"
        if response_last_modified is not None
        else "FETCHED_PUBLICATION_METADATA"
        if publication_metadata_inferred_date is not None
        else "DOCUMENT_CONTENT_INFERENCE"
    )
    document_id = stable_intelligence_id(
        "SGDOC",
        {
            "target_id": target_id,
            "content_hash": content_hash,
            "published_at": published.isoformat() if published else None,
        },
    )
    fetched_at = result.fetched_at.isoformat() if result.fetched_at else as_of_date.isoformat()
    document = {
        "schema_version": "e2r_v5_source_graph_document_v1",
        "document_id": document_id,
        "target_id": target_id,
        "as_of_date": as_of_date.isoformat(),
        "canonical_url": url,
        "discovery_urls": [url],
        "title": candidate.get("title"),
        "source_family": source_family,
        "source_family_observations": [source_family],
        "source_provider": type(page_fetcher).__name__,
        "published_at": published.isoformat() if published else None,
        "available_at": published.isoformat() if published else None,
        "publication_date_source": publication_date_source,
        "response_last_modified_at": (
            response_last_modified_at.isoformat()
            if isinstance(response_last_modified_at, (date, datetime))
            else None
        ),
        "publication_metadata_parts": list(publication_metadata_parts),
        "publication_metadata_semantics_version": getattr(
            result,
            "publication_metadata_semantics_version",
            None,
        ),
        "text_complete": getattr(result, "text_complete", True) is True,
        "original_text_chars": int(
            getattr(result, "original_text_chars", None) or len(text)
        ),
        "returned_text_chars": int(
            getattr(result, "returned_text_chars", None) or len(text)
        ),
        "text_cache_semantics_version": getattr(
            result,
            "text_cache_semantics_version",
            None,
        ),
        "text_extraction_semantics_version": getattr(
            result,
            "text_extraction_semantics_version",
            None,
        ),
        "fetched_at": fetched_at,
        "content_type": result.content_type,
        "content_hash": content_hash,
        "content_text": text,
        "query_ids": list(candidate.get("query_ids") or ()),
        "objective_ids": list(candidate.get("objective_ids") or ()),
        "requested_source_families": list(
            candidate.get("requested_source_families") or ()
        ),
        "source_independence_group": _source_independence_group(url, source_family),
        "verified_official_discovery_urls": (
            [url] if source_family in SOURCE_FAMILY_CLASSES["OFFICIAL"] else []
        ),
        "referenced_urls": list(evidence_reference_urls),
        "referenced_document_ids": [],
        "full_fetch_performed": True,
        "snippet_only": False,
        "snippet_used_as_document": False,
        "snippet_evidence_eligible": False,
        "evidence_eligible": True,
        "evidence_os_ingest_eligible": True,
        "parser_field_direct_score_authority": False,
        "production_score_authority": False,
    }
    return (
        _fetch_record(fetch_id, candidate, "FULL_DOCUMENT_FETCHED", None, content_hash, document_id),
        document,
        None,
    )


def _fetch_record(
    fetch_id: str,
    candidate: Mapping[str, Any],
    disposition: str,
    error: str | None,
    content_hash: str | None = None,
    document_id: str | None = None,
) -> dict[str, Any]:
    return {
        "schema_version": "e2r_v5_source_graph_fetch_record_v1",
        "fetch_id": fetch_id,
        "candidate_id": candidate.get("candidate_id"),
        "url": candidate.get("url"),
        "query_ids": list(candidate.get("query_ids") or ()),
        "objective_ids": list(candidate.get("objective_ids") or ()),
        "disposition": disposition,
        "provider_error": error,
        "content_hash": content_hash,
        "document_id": document_id,
        "full_fetch_attempted": True,
        "snippet_used_as_document": False,
        "score_authority": False,
    }


